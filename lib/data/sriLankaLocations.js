// Get all districts as an array
export const getAllDistricts = () => {
  const districts = [];
  Object.values(sriLankaDistricts).forEach(districtList => {
    districts.push(...districtList);
  });
  return districts.sort();
};

// Get cities for a specific district
export const getCitiesForDistrict = (district) => {
  return districtCities[district] || [];
};

// Get province for a district
export const getProvinceForDistrict = (district) => {
  for (const [province, districts] of Object.entries(sriLankaDistricts)) {
    if (districts.includes(district)) {
      return province;
    }
  }
  return null;
};
